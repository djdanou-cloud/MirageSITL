//! Independent annular momentum and manufactured blade-load oracles.
use mirage_bet::{
    blade::RotorGeometry,
    polar::PolarTable,
    propeller::PropellerCondition,
    propeller_bem::{prandtl_loss, steady_annular, BemOptions},
};
use std::f64::consts::PI;

#[test]
fn loss_limits_and_disabled_identity() {
    assert_eq!(prandtl_loss(2, 0.5, 1.0, 0.1, 0.2, false, false), 1.0);
    let mid = prandtl_loss(2, 0.5, 1.0, 0.1, 0.2, true, true);
    let tip = prandtl_loss(2, 0.999, 1.0, 0.1, 0.2, true, true);
    let root = prandtl_loss(2, 0.1001, 1.0, 0.1, 0.2, true, true);
    assert!(0.0 < tip && tip < mid && mid <= 1.0);
    assert!(0.0 < root && root < mid);
}

#[test]
fn manufactured_ring_recovers_axial_and_angular_momentum() {
    // Choose an exact rotor-plane solution, then derive CL/CD from independent
    // annular momentum loads. No goldens are generated by the solver.
    for (speed, axial, swirl) in [(10.0, 3.0, 1.0), (10.0, -1.0, 0.5), (0.0, 3.0, 0.3)] {
        let (rho, radius, r, dr, chord, blades, omega): (f64, f64, f64, f64, f64, u32, f64) =
            (1.2, 1.0, 0.6, 0.8, 0.12, 3, 100.0);
        let (speed, axial, swirl): (f64, f64, f64) = (speed, axial, swirl);
        let phi = (speed + axial).atan2(omega * r - swirl);
        let w2 = (speed + axial).powi(2) + (omega * r - swirl).powi(2);
        let thrust = 4.0 * PI * rho * r * axial * (speed + axial) * dr;
        let torque = 4.0 * PI * rho * r * r * (speed + axial) * swirl * dr;
        let scale = 0.5 * rho * w2 * blades as f64 * chord * dr;
        let cl = (thrust * phi.cos() + torque / r * phi.sin()) / scale;
        let cd = (-thrust * phi.sin() + torque / r * phi.cos()) / scale;
        assert!(cd > 0.0);
        let cl_table = [cl; 8];
        let cd_table = [cd; 8];
        let polar =
            PolarTable::new(&[-PI, PI], &[1.0, 1e9], &[0.0, 1.0], &cl_table, &cd_table).unwrap();
        let g = RotorGeometry {
            blade_count: blades,
            spin_sign: 1,
            radius_m: radius,
            cutout_m: 0.2,
            radius: &[r],
            chord: &[chord],
            twist: &[phi + 0.1],
            width: &[dr],
        };
        let p = steady_annular(
            g,
            polar,
            PropellerCondition {
                rpm: omega * 60.0 / (2.0 * PI),
                advance_ratio: speed / (omega / (2.0 * PI) * 2.0 * radius),
                density_kg_m3: rho,
                viscosity_pa_s: 1.8e-5,
                sound_speed_mps: 340.0,
                collective_rad: 0.0,
            },
            BemOptions {
                tip_loss: false,
                hub_loss: false,
                swirl: true,
            },
        )
        .unwrap();
        assert!(
            p.converged && p.outside_momentum_validity == (axial < 0.0) && p.polar_flags == 0,
            "{p:?}"
        );
        assert!((p.thrust_n - thrust).abs() < 1e-7, "{p:?}");
        assert!((p.power_w - torque * omega).abs() < 1e-5, "{p:?}");
        assert!((p.mean_induced_mps - axial).abs() < 1e-7);
        assert!((p.mean_swirl_mps - swirl).abs() < 1e-7);
        assert!(p.max_relative_residual < 1e-9);
    }
}

#[test]
fn invalid_geometry_and_conditions_are_rejected() {
    let polar = PolarTable::new(
        &[-1.0, 1.0],
        &[1.0, 1e9],
        &[0.0, 1.0],
        &[0.5; 8],
        &[0.01; 8],
    )
    .unwrap();
    let g = RotorGeometry {
        blade_count: 2,
        spin_sign: 1,
        radius_m: 1.0,
        cutout_m: 0.2,
        radius: &[0.6],
        chord: &[0.1],
        twist: &[0.4],
        width: &[0.8],
    };
    let c = PropellerCondition {
        rpm: 0.0,
        advance_ratio: 0.3,
        density_kg_m3: 1.2,
        viscosity_pa_s: 1.8e-5,
        sound_speed_mps: 340.0,
        collective_rad: 0.0,
    };
    assert!(steady_annular(g, polar, c, BemOptions::default()).is_err());
    assert!(steady_annular(
        RotorGeometry { width: &[0.0], ..g },
        polar,
        PropellerCondition { rpm: 1000.0, ..c },
        BemOptions::default()
    )
    .is_err());
}
