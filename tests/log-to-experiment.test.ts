import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { readDataFlash } from '@mirage/dataflash/reader';
import { DataFlashWriter } from '@mirage/dataflash/writer';
import { extractFromLog, logSpan, missingFields, withSupplied, type ExtractionField, type LogExtraction } from '@mirage/analysis/log-to-experiment';
import { logExtractionRecord, logPlanText, validateLogExtraction, type LogPlan } from '../apps/web/src/experiments/log-plan';

// TASK-182. The oracle is pymavlink 2.4.50's reading of the reference log, tests/fixtures/dataflash/reference.json, generated by
// scripts/generate-dataflash-fixtures.py with mavlogdump.py, independently of this repository's reader.

interface Reference { readonly records: { readonly groups: Readonly<Record<string, { readonly columns: readonly string[]; readonly rows: readonly (readonly (number | string)[])[] }>> } }
const BYTES = readFileSync('tests/fixtures/dataflash/sitl-copter.bin');
const reference = JSON.parse(readFileSync('tests/fixtures/dataflash/reference.json', 'utf8')) as Reference;
/** pymavlink's rows of a message, each field by name; its first element is its timestamp, then the columns in order. */
function rowsOf(name: string): Record<string, number>[] {
  const group = reference.records.groups[name];
  if (!group) throw new Error(`No ${name} in the reference`);
  return group.rows.map(row => Object.fromEntries(group.columns.map((column, index) => [column, Number(row[index + 1])])));
}
const lastAt = (rows: readonly Record<string, number>[], timeS: number, keep: (row: Record<string, number>) => boolean = () => true) => {
  const found = rows.filter(row => keep(row) && (row.TimeUS ?? Infinity) * 1e-6 <= timeS).at(-1);
  if (!found) throw new Error('No row at that time');
  return found;
};
const span = logSpan(readDataFlash(new Uint8Array(BYTES)));
if (!span) throw new Error('The reference log has no span');
const extraction = extractFromLog('sitl-copter.bin', BYTES, span);
const field = (e: LogExtraction, key: string): ExtractionField => { const found = e.fields.find(item => item.key === key); if (!found) throw new Error(`No field ${key}`); return found; };

describe('extraction from a real log', () => {
  it('matches pymavlink\'s reading of the reference log at the start of the interval', () => {
    const at = 42.45, e = extractFromLog('sitl-copter.bin', BYTES, { fromS: at, toS: span.toS });
    const origin = lastAt(rowsOf('ORGN'), at), attitude = lastAt(rowsOf('ATT'), at), state = lastAt(rowsOf('XKF1'), at, row => row.C === 0);
    const wind = lastAt(rowsOf('XKF2'), at, row => row.C === 0), baro = lastAt(rowsOf('BARO'), at, row => row.I === 0), battery = lastAt(rowsOf('BAT'), at, row => row.Inst === 0);
    const n = (key: string, row: Record<string, number>, digits: number) => (row[key] ?? NaN).toFixed(digits);
    expect(e.home?.slice(0, 3)).toEqual([origin.Lat, origin.Lng, origin.Alt]);
    expect(e.home?.[3]).toBeCloseTo(attitude.Yaw ?? NaN, 5);
    expect(field(e, 'home').value).toBe(`${n('Lat', origin, 7)}°, ${n('Lng', origin, 7)}°, ${n('Alt', origin, 2)} m`);
    expect(field(e, 'attitude').value).toBe(`roll ${n('Roll', attitude, 2)}°, pitch ${n('Pitch', attitude, 2)}°, yaw ${n('Yaw', attitude, 2)}°`);
    expect(field(e, 'position').value).toBe(`north ${n('PN', state, 2)} m, east ${n('PE', state, 2)} m, down ${n('PD', state, 2)} m`);
    expect(field(e, 'velocity').value).toBe(`north ${n('VN', state, 2)} m/s, east ${n('VE', state, 2)} m/s, down ${n('VD', state, 2)} m/s`);
    expect(field(e, 'wind').value).toBe(`north ${n('VWN', wind, 2)} m/s, east ${n('VWE', wind, 2)} m/s`);
    expect(field(e, 'pressure').value).toBe(`${n('Press', baro, 0)} Pa`);
    expect(field(e, 'temperature').value).toBe(`${n('Temp', baro, 1)} °C`);
    expect(field(e, 'battery').value).toBe(`${n('Volt', battery, 2)} V, ${n('CurrTot', battery, 1)} mAh used`);
    expect(field(e, 'firmware').value).toBe('ArduCopter V4.8.0-dev (8ab6afde)');
    // Every parameter pymavlink reads as differing from its default goes to the run or says why it does not, and no other.
    const group = reference.records.groups.PARM, rows = group?.rows.map(row => ({ name: String(row[2]), value: Number(row[3]), defaultValue: Number(row[4]) })) ?? [];
    const differing = new Map<string, number>();
    for (const row of rows) { if (row.value !== row.defaultValue && !Number.isNaN(row.defaultValue)) differing.set(row.name, row.value); else if (Number.isNaN(row.defaultValue)) differing.set(row.name, row.value); else differing.delete(row.name); }
    expect([...e.parameters, ...e.skipped].map(item => item.name).sort()).toEqual([...differing.keys()].sort());
    for (const item of [...e.parameters, ...e.skipped]) expect(item.value, item.name).toBe(differing.get(item.name));
    expect(rows.length).toBeGreaterThan(100);
  });
  it('names every field extracted, user-supplied or missing, each extracted one with its source message', () => {
    for (const item of extraction.fields) {
      expect(['extracted', 'user-supplied', 'missing'], item.key).toContain(item.status);
      if (item.status === 'missing') { expect(item.value, item.key).toBeNull(); expect(item.source, item.key).toBeNull(); }
      else { expect(item.value, item.key).not.toBeNull(); expect(item.source, item.key).not.toBeNull(); }
    }
    expect(field(extraction, 'home').source).toBe('ORGN');
    expect(field(extraction, 'attitude').source).toBe('ATT');
    expect(field(extraction, 'position').source).toBe('XKF1, core 0');
    expect(field(extraction, 'parameters').source).toBe('PARM');
    expect(field(extraction, 'wind').source).toBe('XKF2, core 0');
    expect(field(extraction, 'firmware').source).toBe('VER');
  });
  it('always discloses the aircraft as missing, and turbulence, and says what it cannot use', () => {
    expect(missingFields(extraction).map(item => item.key)).toEqual(expect.arrayContaining(['aircraft', 'turbulence']));
    expect(field(extraction, 'position').note).toContain('starts on the ground');
    expect(field(extraction, 'wind').note).toContain('estimate');
  });
  it('sends only what differs from its default, and never the run\'s own SITL settings or the frame', () => {
    expect(extraction.parameters.length).toBeGreaterThan(0);
    for (const parameter of extraction.parameters) {
      expect(parameter.value, parameter.name).not.toBe(parameter.defaultValue);
      expect(parameter.name).not.toMatch(/^(SIM_|STAT_|FRAME_|SERVO\d|LOG_|SCR_)/);
    }
    expect(extraction.skipped.some(item => item.name.startsWith('SIM_'))).toBe(true);
  });
  it('refuses an interval outside the log, and takes one that overlaps it', () => {
    expect(() => extractFromLog('a', BYTES, { fromS: span.toS + 1, toS: span.toS + 2 })).toThrow('does not lie in this log');
    expect(() => extractFromLog('a', BYTES, { fromS: 5, toS: 3 })).toThrow('does not lie in this log');
    expect(extractFromLog('a', BYTES, { fromS: 0, toS: span.fromS + 0.1 }).interval.fromS).toBe(0);
  });
  it('marks a user-supplied field as such, and refuses to overwrite what the log gives', () => {
    const supplied = withSupplied(extraction, 'aircraft', 'Quad X, version 1');
    expect(field(supplied, 'aircraft')).toMatchObject({ status: 'user-supplied', value: 'Quad X, version 1', source: 'the user' });
    expect(() => withSupplied(extraction, 'home', 'elsewhere')).toThrow('not missing');
  });
});

describe('the record a run keeps of its log', () => {
  const two: LogExtraction = { ...extraction, parameters: [{ name: 'ATC_RAT_RLL_P', value: 0.2, defaultValue: 0.135 }, { name: 'NOT_IN_THIS_BUILD', value: 1, defaultValue: 0 }] };
  const plan: LogPlan = { logSha256: 'a'.repeat(64), profileSha256: 'b'.repeat(64), extraction: two };
  const experimentSha256 = 'c'.repeat(64);
  it('says which settings the run really took, and why the others stayed out', () => {
    const record = logExtractionRecord(plan, experimentSha256, new Set(['ATC_RAT_RLL_P']));
    expect(record.parameters.map(parameter => parameter.name)).toEqual(['ATC_RAT_RLL_P']);
    expect(record.skipped).toHaveLength(two.skipped.length + 1);
    expect(record.skipped.find(item => item.name === 'NOT_IN_THIS_BUILD')?.why).toContain('chosen build');
    expect(validateLogExtraction(JSON.parse(JSON.stringify(record)))).toEqual(record);
  });
  it('does not promise settings or a home the log cannot give', () => {
    expect(logPlanText(two)).toContain('its home and up to 2 of its settings');
    expect(logPlanText({ ...two, home: null })).toContain("the Run tab's home, because the log does not give one");
  });
  it('refuses a stored record that says a field is missing and still gives it a value', () => {
    const record = JSON.parse(JSON.stringify(logExtractionRecord(plan, experimentSha256, new Set()))) as { fields: { status: string }[] };
    const held = record.fields.find(item => item.status === 'extracted');
    if (!held) throw new Error('The reference log gives no field');
    held.status = 'missing';
    expect(() => validateLogExtraction(record)).toThrow('Invalid log extraction');
    expect(() => validateLogExtraction({ schemaVersion: 2 })).toThrow('schemaVersion must be 1');
    expect(() => validateLogExtraction({ ...record, experimentSha256: 'not a hash' })).toThrow('experimentSha256');
  });
});

describe('a log that holds little', () => {
  it('lists what is missing and invents nothing', () => {
    const writer = new DataFlashWriter();
    writer.append({ kind: 'event', timeUs: 1_000_000, event: 'note', text: 'a log of nothing much' });
    writer.append({ kind: 'event', timeUs: 2_000_000, event: 'note', text: 'and again' });
    const bare = extractFromLog('bare.bin', writer.bytes(), { fromS: 1, toS: 2 });
    expect(bare.home).toBeNull();
    expect(bare.parameters).toEqual([]);
    expect(bare.modes).toEqual([]);
    expect(bare.commands).toEqual([]);
    for (const key of ['home', 'attitude', 'position', 'velocity', 'battery', 'parameters', 'modes', 'commands', 'pilot', 'wind', 'pressure', 'temperature', 'aircraft', 'firmware', 'frame']) {
      expect(field(bare, key).status, key).toBe('missing');
    }
  });
  it('refuses a file with no timed records', () => {
    expect(() => extractFromLog('x', new DataFlashWriter().bytes(), { fromS: 0, toS: 1 })).toThrow('no timed records');
  });
});
