import { it } from "vitest";
import { nodeCheck } from "./support/node-evidence";
it("GPU analysis enforces full duration, real hardware, features and the accepted frame/memory limits", () => nodeCheck(`
import {assessGpu} from './scripts/bench-render.mjs';
import {assertDisplaySurface,classifyGpuDevice,decideGpuAcceptance,displayRefreshHz,featuresHeld,peakResidency,profileFitsDisplay} from './scripts/gpu-trace.mjs';
const v={schemaVersion:1,source:'hardware',device:'M4',gpu:'Apple M4',os:'macOS',browser:'schema-test-only',powerMode:'AC',backend:'webgl2',fps:60,width:1920,height:1080,dpr:1,warmupS:60,durationS:600,visible:true,production:true,terrain:true,fpv:true,thermal:true,frameMs:Array(40000).fill(15),gpuBytes:1000000,cpuBytes:1000000};
assert.equal(assessGpu(v).metrics.p99FrameMs,15);
assert.equal(assessGpu({...v,gpu:'SwiftShader'}).status,'BLOCKED_EXTERNAL');
assert.equal(assessGpu({...v,frameMs:Array(30000).fill(20)}).status,'FAIL');
assert.throws(()=>assessGpu({...v,frameMs:[15]}));
assert.throws(()=>assessGpu({...v,thermal:false}));
assert.equal(assessGpu({...v,gpuBytes:3*1024**3}).status,'FAIL');
assert.equal(classifyGpuDevice('ANGLE (Apple, ANGLE Metal Renderer: Apple M4, Unspecified Version)','Apple M4'),'M4');
assert.equal(classifyGpuDevice('Google SwiftShader','Apple M4'),'software');
assert.equal(classifyGpuDevice('ANGLE (NVIDIA, NVIDIA GeForce RTX 4050 Laptop GPU Direct3D11)','13th Gen Intel'),'RTX4050');
assert.equal(classifyGpuDevice('Apple M3','Apple M3'),'other');
assert.deepEqual(peakResidency([{gpuBytes:10,cpuBytes:4},{gpuBytes:3,cpuBytes:8}]),{gpuBytes:10,cpuBytes:8});
assert.equal(featuresHeld([{terrain:true,fpv:true,thermal:true},{terrain:true,fpv:false,thermal:true}]),false);
const full={gpu:'Apple M4',hostModel:'Apple M4',os:'macOS',browser:'schema-test-only',powerMode:'AC',backend:'webgl2',fps:60,warmupS:60,measuredS:600,durationS:600,featuresHeld:true,visible:true,width:1920,height:1080,dpr:1,frameMs:Array(40000).fill(15),gpuBytes:1000,cpuBytes:1000};
assert.equal(decideGpuAcceptance(full).status,'PASS');
assert.equal(decideGpuAcceptance({...full,backend:'webgpu'}).status,'BLOCKED_EXTERNAL');
assert.equal(decideGpuAcceptance({...full,gpu:'SwiftShader'}).status,'BLOCKED_EXTERNAL');
assert.equal(decideGpuAcceptance({...full,measuredS:8,durationS:8,frameMs:[15]}).status,'BLOCKED_EXTERNAL');
assert.equal(decideGpuAcceptance({...full,featuresHeld:false}).status,'BLOCKED_EXTERNAL');
assert.equal(decideGpuAcceptance({...full,frameMs:Array(40000).fill(20)}).status,'FAIL');
const n=35971; const accepted=Array(n).fill(16.679999999993015);
for (let i=Math.ceil(n*0.99)-1;i<n;i++) accepted[i]=17.665000000037253;
const sum=a=>a.reduce((s,x)=>s+x,0);
assert.equal(assessGpu({...v,frameMs:accepted,durationS:sum(accepted)/1000}).status,'PASS');
const cut=Math.ceil(n*0.99)-1; const over=accepted.map((x,i)=>i>=cut?17.666:x);
assert.equal(assessGpu({...v,frameMs:over,durationS:sum(over)/1000}).status,'FAIL');
assert.ok(Math.abs(displayRefreshHz(Array(90).fill(1000/59.94))-59.94)<1e-9);
assert.equal(profileFitsDisplay(59.88,60),true);
assert.equal(profileFitsDisplay(59.94,60),true);
assert.equal(profileFitsDisplay(58.5,60),true);
assert.equal(profileFitsDisplay(58,60),false);
assert.equal(profileFitsDisplay(57.9,60),false);
assert.equal(profileFitsDisplay(60,120),false);
assert.equal(profileFitsDisplay(118.9,120),false);
assert.equal(profileFitsDisplay(120,120),true);
assert.throws(()=>displayRefreshHz([16.6]));
assert.throws(()=>assertDisplaySurface({innerWidth:0,innerHeight:800,screenWidth:1280,screenHeight:800,dpr:2}));
assert.doesNotThrow(()=>assertDisplaySurface({innerWidth:1920,innerHeight:1080,screenWidth:1920,screenHeight:1080,dpr:1}));
`));
